-- Вход не выбирается у сервиса.
--
-- Входная нода — это дверь, через которую устройство стучится, а не маршрут:
-- страну и путь решает нода выхода. Каждый живой вход обслуживает все сервисы,
-- а его адрес уходит в ответ DNS вместе с адресами остальных входов, чтобы
-- устройство само перешло на следующий, если один лёг.
--
-- Прежние привязки входов удаляем: они больше ни на что не влияют, а
-- оставленные молча создавали бы впечатление, что выбор всё ещё работает.
DELETE FROM service_nodes sn
 USING nodes n
 WHERE n.id = sn.node_id AND n.role = 'ingress';
